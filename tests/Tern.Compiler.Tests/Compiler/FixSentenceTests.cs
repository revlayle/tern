using System.Text;
using System.Text.RegularExpressions;
using Tern.Compiler.Tools;

namespace Tern.Compiler.Tests;

/// <summary>
/// Every error message says how to fix it, in a sentence that starts with a fix verb (CLAUDE.md), so
/// that <c>tern --json</c> gives a suggestion (M23). The test reads the compiler's source: each message
/// given to <c>new CompileError(pos, ...)</c> or the interpreter's <c>Error(pos, ...)</c>, with each
/// branch of a <c>?:</c> as its own message and the values put in (<c>{...}</c>) shown as <c>{}</c>.
/// A message with no fix sentence is listed in <see cref="NoFix"/> with the reason.
/// Spec 13 (compiler design).
/// </summary>
public class FixSentenceTests
{
    /// <summary>Messages that have no fix sentence that helps, and why.</summary>
    private static readonly Dictionary<string, string> NoFix = new()
    {
        // Another error's text, with a note or a place added: that error has the fix.
        ["{}"] = "another error's text, passed on with a note (called from, generated by) or as it is",
        ["{} (assert at {})"] = "the program's own assert message, reported where the parameter was set",
        // The message names what to write; a fix sentence would only say it again.
        ["Expected {}, found {}"] = "the parser's general error, which names what to write",
        ["Expected an expression, found {}"] = "a value is missing; which one depends on what the line was meant to say",
    };

    [Fact]
    public void Every_error_has_a_fix_sentence_or_is_listed()
    {
        var missing = new List<string>();
        var found = new HashSet<string>();
        foreach (var (file, line, message) in Messages())
        {
            found.Add(message);
            if (Diagnostic.Split(message).Suggestion is null && !message.Contains(". {}") && !NoFix.ContainsKey(message))
                missing.Add($"{file}:{line}: {message}");
        }
        Assert.True(missing.Count == 0, $"{missing.Count} errors have no fix sentence:\n" + string.Join("\n", missing));
        var stale = NoFix.Keys.Where(k => !found.Contains(k)).ToList();
        Assert.True(stale.Count == 0, "Listed in NoFix but no longer in the compiler:\n" + string.Join("\n", stale));
    }

    [Fact]
    public void The_scan_finds_the_messages()
    {
        var messages = Messages().Select(m => m.Message).ToHashSet();
        Assert.True(messages.Count > 400, $"only {messages.Count} messages found");
        Assert.Contains("'{}' is not declared. Check the spelling, or declare it", messages);
        Assert.Contains("Expected {}, found {}. Convert with 'as {}'", messages);
        // Both branches of a ?: are messages.
        Assert.Contains("Only the program's main file has 'fn main()'; '{}' is a module. Rename the function", messages);
        Assert.Contains("Expected {}, found {}", messages);
    }

    // ---------- Reading the messages from the compiler's source ----------

    private static string CompilerSource()
    {
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
        {
            var path = Path.Combine(dir.FullName, "src", "Tern.Compiler");
            if (Directory.Exists(path)) return path;
        }
        throw new DirectoryNotFoundException("src/Tern.Compiler not found");
    }

    /// <summary>Where errors are made: the message is the second argument.</summary>
    private static readonly Regex ErrorStart = new(@"new CompileError\(|\bnew\((?=[\w.]*[pP]os\w*, )|(?<![\w.])Error\((?=[\w.]*[pP]os\w*, )");

    private static IEnumerable<(string File, int Line, string Message)> Messages()
    {
        var root = CompilerSource();
        foreach (var path in Directory.GetFiles(root, "*.cs", SearchOption.AllDirectories).Order(StringComparer.Ordinal))
        {
            if (path.Contains($"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}") || path.Contains($"{Path.DirectorySeparatorChar}bin{Path.DirectorySeparatorChar}")) continue;
            var src = File.ReadAllText(path);
            foreach (Match m in ErrorStart.Matches(src))
            {
                var tokens = Arguments(src, m.Index + m.Length);
                int comma = tokens.FindIndex(t => t.Kind == ',');
                if (comma < 0) continue;
                var message = tokens[(comma + 1)..];
                if (!message.Any(t => t.Kind == '"')) continue;   // built elsewhere
                int pos = 0;
                foreach (var text in Expression(message, ref pos).Distinct())
                    yield return (Path.GetRelativePath(root, path), src[..m.Index].Count(c => c == '\n') + 1, text);
            }
        }
    }

    /// <summary>A token of a C# expression: '"' a string (Text: its characters, {} for each value), '(' ')' '?' ':' '+' ',', or 'x' anything else.</summary>
    private readonly record struct Token(char Kind, string Text = "");

    /// <summary>The tokens of an argument list from <paramref name="i"/> to its closing ')', at the top level of it.</summary>
    private static List<Token> Arguments(string s, int i)
    {
        var tokens = new List<Token>();
        int depth = 0, braces = 0;
        while (i < s.Length)
        {
            char c = s[i];
            if (c == '"' || (c is '$' or '@' && i + 1 < s.Length && s[i + 1] is '"' or '$' or '@'))
            {
                tokens.Add(new Token('"', ReadString(s, ref i)));
                continue;
            }
            if (c == '\'') { SkipChar(s, ref i); tokens.Add(new Token('x')); continue; }
            i++;
            // A property pattern (e is CallExpr { Name: "label" }) is one value.
            if (c == '{') braces++;
            if (braces > 0)
            {
                if (c == '}') braces--;
                tokens.Add(new Token('x'));
                continue;
            }
            switch (c)
            {
                case '(': depth++; tokens.Add(new Token('(')); break;
                case ')':
                    if (depth-- == 0) return tokens;
                    tokens.Add(new Token(')'));
                    break;
                case '?' when i < s.Length && s[i] is '?' or '.': i++; tokens.Add(new Token('x')); break;
                case ',' when depth > 0: tokens.Add(new Token('x')); break;   // inside the first argument: new SourcePos(1, 1)
                case '?' or ':' or '+' or ',': tokens.Add(new Token(c)); break;
                default:
                    if (!char.IsWhiteSpace(c)) tokens.Add(new Token('x'));
                    break;
            }
        }
        return tokens;
    }

    private static void SkipChar(string s, ref int i)
    {
        i++;
        if (s[i] == '\\') i++;
        i++;
        while (s[i] != '\'') i++;
        i++;
    }

    /// <summary>Reads a string literal at <paramref name="i"/> ($"...", @"...", "..."); a value put in is {}.</summary>
    private static string ReadString(string s, ref int i)
    {
        bool interpolated = false, verbatim = false;
        while (s[i] is '$' or '@') { if (s[i] == '$') interpolated = true; else verbatim = true; i++; }
        i++;   // the quote
        var sb = new StringBuilder();
        while (true)
        {
            char c = s[i++];
            if (c == '"')
            {
                if (verbatim && s[i] == '"') { sb.Append('"'); i++; continue; }
                return sb.ToString();
            }
            if (c == '\\' && !verbatim) { sb.Append(s[i] switch { 'n' => '\n', var e => e }); i++; continue; }
            if (interpolated && c == '{')
            {
                if (s[i] == '{') { sb.Append('{'); i++; continue; }
                SkipHole(s, ref i);
                sb.Append("{}");
                continue;
            }
            if (interpolated && c == '}' && s[i] == '}') { sb.Append('}'); i++; continue; }
            sb.Append(c);
        }
    }

    /// <summary>Skips a value put into an interpolated string, to after its '}'.</summary>
    private static void SkipHole(string s, ref int i)
    {
        int depth = 0;
        while (true)
        {
            char c = s[i];
            if (c == '"' || (c is '$' or '@' && s[i + 1] is '"' or '$' or '@')) { ReadString(s, ref i); continue; }
            if (c == '\'') { SkipChar(s, ref i); continue; }
            i++;
            if (c == ':' && depth == 0)
            {
                // A format, such as X4 or +0;-0;'': text up to the '}'. (A ?: in a value needs parentheses.)
                while (s[i++] != '}') { }
                return;
            }
            if (c is '(' or '{' or '[') depth++;
            else if (c is ')' or ']') depth--;
            else if (c == '}' && depth-- == 0) return;
        }
    }

    // A small parser for the message expression: each result is one message it can give.
    // expr := concat ('?' expr ':' expr)?    concat := primary ('+' primary)*
    // primary := string | '(' expr ')' | other tokens, with call arguments, which give {}

    private static List<string> Expression(List<Token> t, ref int p)
    {
        var condition = Concat(t, ref p);
        // A condition with more in it (e is CallExpr { Name: "label" }): up to its '?'.
        int q = p, depth = 0;
        for (; q < t.Count && !(depth == 0 && t[q].Kind is '?' or ':' or ')'); q++) depth += t[q].Kind switch { '(' => 1, ')' => -1, _ => 0 };
        if (q > p && q < t.Count && t[q].Kind == '?') p = q;
        if (p < t.Count && t[p].Kind == '?')
        {
            p++;
            var yes = Expression(t, ref p);
            if (p < t.Count && t[p].Kind == ':') p++;
            var no = Expression(t, ref p);
            return [.. yes, .. no];
        }
        return condition;
    }

    private static List<string> Concat(List<Token> t, ref int p)
    {
        var result = Primary(t, ref p);
        while (p < t.Count && t[p].Kind == '+')
        {
            p++;
            var next = Primary(t, ref p);
            result = result.SelectMany(a => next.Select(b => a + b)).ToList();
        }
        return result;
    }

    private static List<string> Primary(List<Token> t, ref int p)
    {
        if (p >= t.Count) return [""];
        switch (t[p].Kind)
        {
            case '"':
                return [t[p++].Text];
            case '(':
            {
                p++;
                var inner = Expression(t, ref p);
                if (p < t.Count && t[p].Kind == ')') p++;
                return inner;
            }
            default:
                // A name, a call, a member: its value.
                while (p < t.Count && t[p].Kind is 'x' or '(')
                {
                    if (t[p].Kind == '(')
                    {
                        int depth = 0;
                        do depth += t[p].Kind switch { '(' => 1, ')' => -1, _ => 0 }; while (++p < t.Count && depth > 0);
                    }
                    else p++;
                }
                return ["{}"];
        }
    }
}
