using System.Text;

namespace Tern.Compiler.Tests;

/// <summary>
/// Six routines of the standard library written in assembly, each next to the same routine in plain Tern
/// (<c>tests/benchmarks/library/&lt;routine&gt;.lib.tern</c> calls the library, <c>.plain.tern</c> defines its own), for
/// <c>tests/benchmarks/analysis.md</c>. Both programs run the same driver and are checked against a C# computation. The
/// plain versions are measurements and stay out of the library. With <c>TERN_COMPARE=1</c> the bytes (driver and routine, from
/// <c>main</c> on) and cycles are written to <c>library.md</c>.
/// </summary>
public class LibraryGapTests
{
    private static readonly Dictionary<string, Action<Results>> Checks = new()
    {
        ["mul8"] = r =>
        {
            ushort acc = 0; byte b = 0;
            for (int i = 0; i < 256; i++) { b = (byte)(b + 37); acc += (ushort)(i * b); }
            Assert.Equal(acc, r.U16("acc"));
        },
        ["div8"] = r =>
        {
            ushort acc = 0; byte d = 1;
            for (int i = 0; i < 256; i++) { d = (byte)((d + 37) | 1); acc += (ushort)(i / d + i % d); }
            Assert.Equal(acc, r.U16("acc"));
        },
        ["mul16"] = r =>
        {
            ushort acc = 0, m = 1;
            for (int i = 0; i < 100; i++) { m = (ushort)(m + 1237); acc ^= (ushort)(m * (77 + i)); }
            Assert.Equal(acc, r.U16("acc"));
        },
        ["abs16"] = r =>
        {
            ushort acc = 0; short x = -32000;
            for (int i = 0; i < 256; i++) { x = (short)(x + 421); acc += (ushort)Math.Abs((int)x); }
            Assert.Equal(acc, r.U16("acc"));
        },
        ["add32"] = r =>
        {
            uint sum = 100u * 0x0003_9E37;
            for (int i = 0; i < 4; i++) Assert.Equal((byte)(sum >> (8 * i)), r.U8("sum", i));
        },
        ["bcd_add"] = r =>
        {
            // 100 x 000219 37 (bytes low first: $37, $19, $02) in packed decimal: 100 * 21937 = 2193700.
            Assert.Equal(new byte[] { 0x00, 0x37, 0x19, 0x02 }, Enumerable.Range(0, 4).Select(i => r.U8("score", i)).ToArray());
        },
    };

    [Fact]
    public void Library_routines_and_their_plain_Tern_versions_give_the_same_results()
    {
        string dir = Path.Combine(BenchmarkTests.Directory_, "library");
        var sb = new StringBuilder();
        sb.AppendLine("# Library routines against plain Tern");
        sb.AppendLine();
        sb.AppendLine("Generated by `LibraryGapTests` (`TERN_COMPARE=1 dotnet test --filter LibraryGapTests`); see `analysis.md`. Each program is the");
        sb.AppendLine("same driver calling the library's assembly routine (`.lib.tern`) or a plain Tern function (`.plain.tern`). Bytes are the");
        sb.AppendLine("driver and the routine, from `main` on; cycles are `main` to its return.");
        sb.AppendLine();
        sb.AppendLine("| routine | asm bytes | asm cycles | plain bytes | plain cycles |");
        sb.AppendLine("|---|--:|--:|--:|--:|");
        foreach (var (name, check) in Checks)
        {
            var lib = ComparisonTests.MeasureTern(Path.Combine(dir, name + ".lib.tern"), check);
            var plain = ComparisonTests.MeasureTern(Path.Combine(dir, name + ".plain.tern"), check);
            sb.AppendLine($"| {name} | {lib.Bytes} | {lib.Cycles:N0} | {plain.Bytes} | {plain.Cycles:N0} |");
        }
        if (Environment.GetEnvironmentVariable("TERN_COMPARE") == "1") File.WriteAllText(Path.Combine(dir, "..", "library.md"), sb.ToString());
    }
}
