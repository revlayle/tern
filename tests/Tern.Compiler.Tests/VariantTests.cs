using System.Text;

namespace Tern.Compiler.Tests;

/// <summary>
/// The same benchmark task written another way in Tern (<c>tests/benchmarks/variants/&lt;task&gt;.&lt;tag&gt;.tern</c>), for the
/// gap analysis in <c>tests/benchmarks/analysis.md</c>. Each variant is checked against the task's C# result, so it
/// does the same work. Its bytes and cycles are written to <c>variants.md</c> when <c>TERN_COMPARE=1</c>; they are
/// measurements, not baselines, and a change in the compiler does not fail this test.
/// </summary>
public class VariantTests
{
    [Fact]
    public void Every_variant_does_the_work_of_its_task()
    {
        string dir = BenchmarkTests.Directory_;
        var files = Directory.GetFiles(Path.Combine(dir, "variants"), "*.tern").Order(StringComparer.Ordinal).ToList();
        var sb = new StringBuilder();
        sb.AppendLine("# Variants");
        sb.AppendLine();
        sb.AppendLine("Generated by `VariantTests` (`TERN_COMPARE=1 dotnet test --filter VariantTests`). The same tasks written another way in Tern;");
        sb.AppendLine("see `analysis.md`. Bytes and cycles are counted as in `comparison.md`.");
        sb.AppendLine();
        sb.AppendLine("| variant | bytes | cycles | task bytes | task cycles |");
        sb.AppendLine("|---|--:|--:|--:|--:|");
        foreach (var file in files)
        {
            string task = Path.GetFileName(file).Split('.')[0];
            var v = ComparisonTests.MeasureTern(file, task);
            var t = ComparisonTests.MeasureTern(Path.Combine(dir, task + ".tern"), task);
            sb.AppendLine($"| {Path.GetFileNameWithoutExtension(file)} | {v.Bytes} | {v.Cycles:N0} | {t.Bytes} | {t.Cycles:N0} |");
        }
        if (Environment.GetEnvironmentVariable("TERN_COMPARE") == "1")
        {
            File.WriteAllText(Path.Combine(dir, "variants.md"), sb.ToString());
            // How often each instruction ran, for the numbers in analysis.md.
            Directory.CreateDirectory(Path.Combine(dir, "profiles"));
            foreach (var task in BenchmarkTests.Checks.Keys)
            {
                File.WriteAllText(Path.Combine(dir, "profiles", task + ".txt"), ComparisonTests.Profile(Path.Combine(dir, task + ".tern")));
                File.WriteAllText(Path.Combine(dir, "profiles", task + ".asm.txt"), ComparisonTests.AsmProfile(dir, task));
            }
            foreach (var file in files)
                File.WriteAllText(Path.Combine(dir, "profiles", Path.GetFileNameWithoutExtension(file) + ".txt"), ComparisonTests.Profile(file));
        }
    }
}
