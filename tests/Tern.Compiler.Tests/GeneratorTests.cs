    // ---------- Addresses and the calling block's labels (decision 2026-11-11, questions 100, 103) ----------

    [Fact]
    public void A_generator_copies_into_a_buffer_the_compiler_places()
    {
        var r = Run.Program("""
            data src: [u8; 6] = [11, 22, 33, 44, 55, 66]
            var buf: [u8; 8]
            var p: ptr u8 @ zp
            var called: u8
            fn mark() { called = 9 }

            const fn copy_to(dst: label, n: int) {
                for i in 0..n {
                    emit {
                        lda src + i
                        sta dst + i + 1
                    }
                }
            }
            const fn point_at(target: label, f: label) {
                emit {
                    lda #target.lo
                    sta p
                    lda #target.hi
                    sta p + 1
                    jsr f
                }
            }
            const fn via_local() {
                var first = addr(buf)
                emit { stx first }
            }

            fn main() {
                asm {
                    copy_to(addr(buf), 6)
                    point_at(addr(buf), addr(mark))
                    ldx #7
                    via_local()
                }
            }
            """);
        Assert.Equal([7, 11, 22, 33, 44, 55, 66, 0], r.Ram.Bytes.AsSpan(r.Address("buf"), 8).ToArray());
        Assert.Equal(r.Address("buf"), r.U16("p"));
        Assert.Equal(9, r.U8("called"));
    }

    [Theory]
