    private readonly DirectoryInfo _dir = Directory.CreateTempSubdirectory("tern");

    public void Dispose() => _dir.Delete(recursive: true);

    private string MainPath => Path.Combine(_dir.FullName, "main.tern");

    private void Write(string name, string text) => File.WriteAllText(Path.Combine(_dir.FullName, name), text);

    private static CompileError Error(string source) => Assert.Throws<CompileError>(() => TernCompiler.Compile(source));

    /// <summary>The generator of spec 4.1, with the rows to skip as a list.</summary>
    private const string CopyRows = """
        const fn copy_rows(src: int, dst: int, rows: int, skip: [int; _]) {
            for r in 0..rows {
                var skipped = false
                for k in 0..len(skip) {
                    if skip[k] == r { skipped = true }
                }
                if !skipped {
                    emit {
                        lda src + r * 40, x
                        sta dst + r * 40, x
                    }
                }
            }
        }
        """;

    // ---------- Done when (roadmap M22, part 2) ----------

    [Fact]
    public void An_unrolled_screen_copy_that_skips_given_rows_runs_and_its_listing_shows_each_instructions_source()
    {
        var source = CopyRows + """

            const SCREEN = $0400
            const BACK = $C000

            asm fn shift_left() {
                ldx #0
            .loop:
                copy_rows(SCREEN + 1, BACK, 25, [3, 12, 24])
                inx
                cpx #39
                beq .done
                jmp .loop
            .done:
            }

            fn main() {
                shift_left()
            }
            """;
        var r = Run.Program(source, setup: ram =>
        {
            for (int i = 0; i < 1000; i++) ram.Bytes[0x0400 + i] = (byte)(i * 7 + 1);
            for (int i = 0; i < 1000; i++) ram.Bytes[0xC000 + i] = 0xEE;
        });
        int[] skipped = [3, 12, 24];
        for (int row = 0; row < 25; row++)
            for (int col = 0; col < 40; col++)
            {
                byte expected = skipped.Contains(row) || col == 39 ? (byte)0xEE : (byte)((row * 40 + col + 1) * 7 + 1);
                Assert.True(expected == r.Ram.Bytes[0xC000 + row * 40 + col], $"row {row}, column {col}");
            }

        // 22 copies of lda / sta, each instruction under the emit line it came from and the call.
        var listing = r.Result.Listing;
        var sourceLines = source.ReplaceLineEndings("\n").Split('\n');
        int LineOf(string text) => Array.FindIndex(sourceLines, l => l.Contains(text)) + 1;
        int call = LineOf("copy_rows(SCREEN + 1"), lda = LineOf("lda src + r * 40"), sta = LineOf("sta dst + r * 40");
        Assert.Equal(22, CountOf(listing, $"{lda,4}: lda src + r * 40, x   (generated by line {call})"));
        Assert.Equal(22, CountOf(listing, $"{sta,4}: sta dst + r * 40, x   (generated by line {call})"));
        Assert.Equal(1, CountOf(listing, $"{call,4}: copy_rows(SCREEN + 1, BACK, 25, [3, 12, 24])"));
        var lines = listing.Split('\n');
        int first = Array.FindIndex(lines, l => l.Contains("copy_rows(SCREEN + 1"));
        Assert.Contains($"{lda,4}: lda src + r * 40, x   (generated by line {call})", lines[first + 1]);
        Assert.Contains("lda $0401,x", lines[first + 2]);
        Assert.Contains($"{sta,4}: sta dst + r * 40, x   (generated by line {call})", lines[first + 3]);
        Assert.Contains("sta $C000,x", lines[first + 4]);
    }

    private static int CountOf(string text, string part)
    {
        int count = 0;
        for (int at = text.IndexOf(part, StringComparison.Ordinal); at >= 0; at = text.IndexOf(part, at + 1, StringComparison.Ordinal)) count++;
        return count;
    }

    // ---------- Labels ----------

    [Fact]
    public void Each_emit_has_its_own_local_labels()
    {
        // Each emitted fragment counts one value down to zero and skips the decrement when it is zero.
        var r = Run.Program("""
            var v: [u8; 3]
            const fn floor_at_zero(n: int) {
                for i in 0..n {
                    emit {
                        lda v + i
                        beq .skip
                        dec v + i
                    .skip:
                    }
                }
            }
            fn main() {
                v[0] = 5
                v[2] = 1
                asm {
                    floor_at_zero(3)
                }
            }
            """);
        Assert.Equal([4, 0, 0], new[] { r.U8("v"), r.U8("v", 1), r.U8("v", 2) });
    }

    [Fact]
    public void A_label_value_is_shared_between_fragments_and_generators()
    {
        // A loop built from three fragments: the label is placed in one and used in another, also before it is placed.
        var r = Run.Program("""
            var n: u8
            var out: u8
            const fn back_to(target: label) {
                emit { bne target }
            }
            const fn count(times: int) {
                var top = label()
                var done = label()
                emit {
                    ldx #times
                top:
                    inc out
                    dex
                    beq done
                }
                back_to(top)
                emit {
                done:
                    stx n
                }
            }
            fn main() {
                asm { count(6) }
            }
            """);
        Assert.Equal(6, r.U8("out"));
        Assert.Equal(0, r.U8("n"));
    }

