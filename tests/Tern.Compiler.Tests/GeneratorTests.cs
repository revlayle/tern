using Tern.Compiler.Syntax;

namespace Tern.Compiler.Tests;

/// <summary>Code generators (spec 4.1): <c>emit</c> in a const fn, called on a line of an asm block; <c>label()</c>.</summary>
public sealed class GeneratorTests : IDisposable
{
    private readonly DirectoryInfo _dir = Directory.CreateTempSubdirectory("tern");

    public void Dispose() => _dir.Delete(recursive: true);

    private string MainPath => Path.Combine(_dir.FullName, "main.tern");

    private void Write(string name, string text) => File.WriteAllText(Path.Combine(_dir.FullName, name), text);

    private static CompileError Error(string source) => Assert.Throws<CompileError>(() => TernCompiler.Compile(source));

    /// <summary>The generator of spec 4.1, with the rows to skip as a list.</summary>
    private const string CopyRows = """
        const fn copy_rows(src: int, dst: int, rows: int, skip: [int; _]) {
            for r in 0..rows {
                var skipped = false
                for k in 0..len(skip) {
                    if skip[k] == r { skipped = true }
                }
                if !skipped {
                    emit {
                        lda src + r * 40, x
                        sta dst + r * 40, x
                    }
                }
            }
        }
        """;

    // ---------- Done when (roadmap M22, part 2) ----------

    [Fact]
    public void An_unrolled_screen_copy_that_skips_given_rows_runs_and_its_listing_shows_each_instructions_source()
    {
        var source = CopyRows + """

            const SCREEN = $0400
            const BACK = $C000

            asm fn shift_left() {
                ldx #0
            .loop:
                copy_rows(SCREEN + 1, BACK, 25, [3, 12, 24])
                inx
                cpx #39
                beq .done
                jmp .loop
            .done:
            }

            fn main() {
                shift_left()
            }
            """;
        var r = Run.Program(source, setup: ram =>
        {
            for (int i = 0; i < 1000; i++) ram.Bytes[0x0400 + i] = (byte)(i * 7 + 1);
            for (int i = 0; i < 1000; i++) ram.Bytes[0xC000 + i] = 0xEE;
        });
        int[] skipped = [3, 12, 24];
        for (int row = 0; row < 25; row++)
            for (int col = 0; col < 40; col++)
            {
                byte expected = skipped.Contains(row) || col == 39 ? (byte)0xEE : (byte)((row * 40 + col + 1) * 7 + 1);
                Assert.True(expected == r.Ram.Bytes[0xC000 + row * 40 + col], $"row {row}, column {col}");
            }

        // 22 copies of lda / sta, each instruction under the emit line it came from and the call.
        var listing = r.Result.Listing;
        var sourceLines = source.ReplaceLineEndings("\n").Split('\n');
        int LineOf(string text) => Array.FindIndex(sourceLines, l => l.Contains(text)) + 1;
        int call = LineOf("copy_rows(SCREEN + 1"), lda = LineOf("lda src + r * 40"), sta = LineOf("sta dst + r * 40");
        Assert.Equal(22, CountOf(listing, $"{lda,4}: lda src + r * 40, x   (generated by line {call})"));
        Assert.Equal(22, CountOf(listing, $"{sta,4}: sta dst + r * 40, x   (generated by line {call})"));
        Assert.Equal(1, CountOf(listing, $"{call,4}: copy_rows(SCREEN + 1, BACK, 25, [3, 12, 24])"));
        var lines = listing.Split('\n');
        int first = Array.FindIndex(lines, l => l.Contains("copy_rows(SCREEN + 1"));
        Assert.Contains($"{lda,4}: lda src + r * 40, x   (generated by line {call})", lines[first + 1]);
        Assert.Contains("lda $0401,x", lines[first + 2]);
        Assert.Contains($"{sta,4}: sta dst + r * 40, x   (generated by line {call})", lines[first + 3]);
        Assert.Contains("sta $C000,x", lines[first + 4]);
    }

    private static int CountOf(string text, string part)
    {
        int count = 0;
        for (int at = text.IndexOf(part, StringComparison.Ordinal); at >= 0; at = text.IndexOf(part, at + 1, StringComparison.Ordinal)) count++;
        return count;
    }

    // ---------- Labels ----------

    [Fact]
    public void Each_emit_has_its_own_local_labels()
    {
        // Each emitted fragment counts one value down to zero and skips the decrement when it is zero.
        var r = Run.Program("""
            var v: [u8; 3]
            const fn floor_at_zero(n: int) {
                for i in 0..n {
                    emit {
                        lda v + i
                        beq .skip
                        dec v + i
                    .skip:
                    }
                }
            }
            fn main() {
                v[0] = 5
                v[2] = 1
                asm {
                    floor_at_zero(3)
                }
            }
            """);
        Assert.Equal([4, 0, 0], new[] { r.U8("v"), r.U8("v", 1), r.U8("v", 2) });
    }

    [Fact]
    public void A_label_value_is_shared_between_fragments_and_generators()
    {
        // A loop built from three fragments: the label is placed in one and used in another, also before it is placed.
        var r = Run.Program("""
            var n: u8
            var out: u8
            const fn back_to(target: label) {
                emit { bne target }
            }
            const fn count(times: int) {
                var top = label()
                var done = label()
                emit {
                    ldx #times
                top:
                    inc out
                    dex
                    beq done
                }
                back_to(top)
                emit {
                done:
                    stx n
                }
            }
            fn main() {
                asm { count(6) }
            }
            """);
        Assert.Equal(6, r.U8("out"));
        Assert.Equal(0, r.U8("n"));
    }

    [Theory]
    [InlineData("var top = label()\n    emit { top: }\n    emit { top: }", "This label() is placed twice, first at line 3 (called from line 9). Place it once")]
    [InlineData("var top = label()\n    emit { jmp top }", "This label() is used but never placed (generated by the call at line 8). Place it in an emit with its variable's name and ':', e.g. 'emit { top: }'")]
    [InlineData("var top = 5\n    emit { top: }", "'top' is not a label() value, so it cannot be placed")]
    [InlineData("emit { top: }", "'top' is not a variable of this const fn (called from line 7). Make a label with 'var top = label()', or write a local label '.top:'")]
    [InlineData("emit { bne .loop }", "Label '.loop' is not defined in this emit (called from line 7). A generator cannot use the labels of the asm block that calls it; pass a label() value instead")]
    [InlineData("emit {\n    .a:\n    .a:\n    }", "Label '.a' is defined twice in this emit")]
    public void Label_errors(string body, string expected)
    {
        var e = Error($"const fn g() {{\n    {body}\n}}\nfn main() {{\n    asm {{\n    .loop:\n        g()\n    }}\n}}");
        Assert.Contains(expected, e.Description);
    }

    // ---------- Operands ----------

    [Fact]
    public void Operands_name_variables_data_functions_and_fields_and_call_const_fns()
    {
        var r = Run.Program("""
            struct P { x: u8, y: u8 }
            var p: P
            var buf: [u8; 4]
            var hits: u8
            data table: [u8; 4] = [10, 20, 30, 40]
            fn hit() { hits += 1 }
            const fn twice(n: int) -> int { return n * 2 }
            const fn fill() {
                for i in 0..4 {
                    emit {
                        lda #table[i] + twice(i)
                        sta buf + i
                    }
                }
                emit {
                    lda #<value>
                    sta p.y
                    jsr hit
                    lda #addr_lo
                    sta p.x
                }
            }
            const fn unused() { }
            fn main() {
                asm { fill() }
            }
            """.Replace("#<value>", "#len(table) * 10").Replace("#addr_lo", "#buf.lo"));
        Assert.Equal([10, 22, 34, 46], new[] { r.U8("buf"), r.U8("buf", 1), r.U8("buf", 2), r.U8("buf", 3) });
        Assert.Equal(40, r.U8("p", 1));
        Assert.Equal(1, r.U8("hits"));
        Assert.Equal(r.Address("buf") & 0xFF, r.U8("p"));
    }

    [Fact]
    public void A_generator_in_a_module_names_the_modules_own_variables()
    {
        Write("fx.tern", """
            var count: u8
            const STEP = 3
            const fn bump(times: int) {
                for _ in 0..times {
                    emit {
                        lda count
                        clc
                        adc #STEP
                        sta count
                    }
                }
            }
            """);
        var r = Run.Program("""
            import fx
            var count: u8
            fn main() {
                count = 100
                asm { fx.bump(4) }
            }
            """, sourcePath: MainPath);
        Assert.Equal(12, r.U8("fx.count"));
        Assert.Equal(100, r.U8("count"));
        Assert.Contains("fx.tern:8: adc #STEP   (generated by line 5)", r.Result.Listing);
    }

    [Fact]
    public void A_generator_runs_in_a_plain_asm_block_and_in_an_inline_asm_fn_and_its_effects_count()
    {
        var r = Run.Program("""
            var a: u8
            var b: u8
            const fn store(at: int, value: int) {
                emit {
                    ldy #value
                    sty at
                }
            }
            inline asm fn set_b() {
                store(B, 9)
            }
            const B = $0340
            fn main() {
                for i in 0..2 using X {
                    asm { store($0341, 7) }
                }
                set_b()
                a = 1
            }
            """);
        Assert.Equal(9, r.Ram.Bytes[0x0340]);
        Assert.Equal(7, r.Ram.Bytes[0x0341]);
        Assert.Contains("asm: reads Y, changes Y Z N", r.Result.Listing);
    }

    [Fact]
    public void Generated_code_that_changes_the_loop_register_is_an_error_naming_the_call()
    {
        var e = Error("const fn g() {\n    emit { ldx #0 }\n}\nfn main() {\n    for i in 0..2 using X {\n        asm {\n            g()\n        }\n    }\n}");
        Assert.Equal("This changes X, which holds the loop variable (generated by the call at line 7). Remove 'using X' from the loop, or leave X unchanged", e.Description);
        Assert.Equal(2, e.Pos.Line);
    }

    [Theory]
    [InlineData("emit { lda #v }", "#300 does not fit in a byte (generated by the call at line 7)")]
    [InlineData("emit { lda #v * 0.5 }", "This operand is a real (called from line 7). Use round(x), floor(x), ceil(x) or trunc(x)")]
    [InlineData("emit { lda #[1, 2] }", "This operand is an array, but an instruction takes a number, an address or a label")]
    [InlineData("emit { lda nope }", "'nope' is not declared")]
    [InlineData("emit {\n    g2()\n    }", "A generator is called as a statement of the const fn, not inside 'emit'")]
    [InlineData("while true { }", "'g' did not finish after 10,000,000 steps (called from line 7). Check its loops for one that never ends")]
    [InlineData("for _ in 0..70000 { emit { nop } }", "The generator emitted more than 65536 lines")]
    [InlineData("h()", "'h' returns a value, so the const fns it calls cannot emit assembly (called from line 7). Call the generator from an asm block instead")]
    public void Errors_while_generating(string body, string expected)
    {
        var e = Error($"const fn g() {{\n    var v = 300\n    {body}\n}}\nfn main() {{\n    asm {{\n        g()\n    }}\n}}\nconst fn g2() {{ }}\nconst fn h() -> int {{\n    g2()\n    return 1\n}}"
            .Replace("const fn g2() { }", "const fn g2() { emit { nop } }"));
        Assert.Contains(expected, e.Description);
    }

    [Fact]
    public void A_branch_out_of_range_in_generated_code_names_the_emit_line_and_the_call()
    {
        var e = Error("""
            const fn far() {
                var top = label()
                emit { top: }
                for _ in 0..200 { emit { nop } }
                emit { bne top }
            }
            fn main() {
                asm {
                    far()
                }
            }
            """);
        Assert.Equal(5, e.Pos.Line);
        Assert.StartsWith("Branch to ", e.Description);
        Assert.EndsWith("a branch reaches -128 to 127) (generated by the call at line 9). Use jmp", e.Description);
    }

    [Theory]
    [InlineData("fn main() { g() }", "'g' is a generator, which emits assembly. Call it on a line of its own in an asm block")]
    [InlineData("const K = g()\nfn main() { }", "'g' emits assembly, so it returns no value. Call it on a line of its own in an asm block")]
    [InlineData("fn main() { asm { f() } }", "'f' returns a value, so it is not a generator, which emits assembly. Use its value in an operand, e.g. 'lda #f(...)'")]
    [InlineData("fn main() { asm { round(1.5) } }", "round() is not a generator. Name a const fn that emits assembly on this line, or use the value in an operand")]
    [InlineData("fn r() { }\nfn main() { asm { r() } }", "'r' is a function, which runs on the 6502. Call it with 'jsr r'")]
    [InlineData("fn main() { asm { nope() } }", "'nope' is not declared")]
    [InlineData("fn main() { asm { g(1) } }", "'g' takes 0 argument(s), not 1")]
    [InlineData("var x: u8\nfn main() { asm { k(x) } }\nconst fn k(n: int) { }", "'x' is a variable, whose value is not known at compile time. Use a const or data")]
    [InlineData("const fn e() { }\nconst fn m() -> int {\n    e2()\n    return 1\n}\nconst fn e2() { emit { nop } }\nconst K = m()\nfn main() { }", "'emit' adds instructions to the asm block that calls the generator, but this evaluation is not a generator call (called from line 9). Call the generator on a line of its own in an asm block")]
    public void Calls_of_generators(string source, string expected)
    {
        var e = Error("const fn g() { emit { nop } }\nconst fn f() -> int { return 1 }\n" + source);
        Assert.Contains(expected, e.Description);
    }

    [Fact]
    public void An_emit_fragment_is_parsed_when_the_const_fn_is_read()
    {
        // The emit never runs, since nothing calls the generator, but its typo is reported.
        var e = Error("const fn g() {\n    if false {\n        emit {\n            lda #1\n            sta1 $0400\n        }\n    }\n}\nfn main() { }");
        Assert.Equal("Unknown instruction 'sta1'", e.Description);
        Assert.Equal(5, e.Pos.Line);
    }
}
