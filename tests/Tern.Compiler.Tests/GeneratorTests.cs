    [Fact]
    public void Two_generator_calls_in_one_block_have_their_own_labels()
    {
        // Review M22, finding 1: the same generator twice, with a local label and with label(), and two
        // generators with the same local label name, in one asm block.
        var r = Run.Program("""
            var v: [u8; 4]
            var w: u8
            const fn dec_nz(i: int) {
                emit {
                    lda v + i
                    beq .skip
                    dec v + i
                .skip:
                }
            }
            const fn inc_w(times: int) {
                var top = label()
                emit {
                    ldx #times
                top:
                    inc w
                    dex
                    bne top
                }
            }
            const fn clear_if_one(i: int) {
                emit {
                    lda v + i
                    cmp #1
                    bne .skip
                    lda #0
                    sta v + i
                .skip:
                }
            }
            fn main() {
                v[0] = 3
                v[2] = 1
                v[3] = 5
                asm {
                    dec_nz(0)
                    dec_nz(1)
                    inc_w(2)
                    inc_w(3)
                    clear_if_one(2)
                    clear_if_one(3)
                }
            }
            """);
        Assert.Equal([2, 0, 0, 5], new[] { r.U8("v"), r.U8("v", 1), r.U8("v", 2), r.U8("v", 3) });
