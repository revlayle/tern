    [Fact]
    public void Operands_name_variables_data_functions_and_fields_and_call_const_fns()
    {
        var r = Run.Program("""
            struct P { x: u8, y: u8 }
            var p: P
            var buf: [u8; 4]
            var hits: u8
            data table: [u8; 4] = [10, 20, 30, 40]
            fn hit() { hits += 1 }
            const fn twice(n: int) -> int { return n * 2 }
            const fn fill() {
                for i in 0..4 {
                    emit {
                        lda #table[i] + twice(i)
                        sta buf + i
                    }
                }
                emit {
                    lda #<value>
                    sta p.y
                    jsr hit
                    lda #addr_lo
                    sta p.x
                }
            }
            const fn unused() { }
            fn main() {
                asm { fill() }
            }
            """.Replace("#<value>", "#len(table) * 10").Replace("#addr_lo", "#buf.lo"));
        Assert.Equal([10, 22, 34, 46], new[] { r.U8("buf"), r.U8("buf", 1), r.U8("buf", 2), r.U8("buf", 3) });
        Assert.Equal(40, r.U8("p", 1));
        Assert.Equal(1, r.U8("hits"));
        Assert.Equal(r.Address("buf") & 0xFF, r.U8("p"));
    }

    [Fact]
