using Tern.Compiler.Syntax;
using Tern.Cpu;
using static Tern.Cpu.AddressingMode;

namespace Tern.Compiler.Semantics;

/// <summary>Assembly blocks: operands, addressing modes, and what each block reads and changes.</summary>
public sealed partial class Checker
{
    private void CheckAsm(AsmStmt block)
    {
        ExpandGenerators(block);
        var labels = new Dictionary<string, AsmLabel>();
        foreach (var l in block.Lines.OfType<AsmLabel>())
            if (!labels.TryAdd(l.Name, l))
                throw new CompileError(l.Pos, $"Label '{l.Name}' is defined twice in this block. Rename one of them");

        var effects = new AsmEffects();
        foreach (var ins in block.Lines.OfType<AsmInstruction>())
        {
            try
            {
                ins.Value = ins.Operand is null ? null : AsmOperand(ins.Operand, labels);
                ins.Mode = AsmMode(ins, ins.Value);
                AddEffects(ins, effects);
            }
            catch (CompileError e) when (ins.CalledFrom is { } call)
            {
                // An error in generated code names the emit line and the generator call (spec 4.1).
                throw new CompileError(e.Pos, CompileTime.Interpreter.WithNote(e.Description, $"generated by the call at {CompileTime.Interpreter.Where(call)}"))
                {
                    CalledFrom = call,
                };
            }
        }
        block.Effects = effects;
    }

    /// <summary>Replaces each generator call line with the lines the generator emits (spec 4.1).</summary>
    private void ExpandGenerators(AsmStmt block)
    {
        if (!block.Lines.Any(l => l is AsmGeneratorCall)) return;
        var lines = new List<AsmLine>();
        int numbers = 0;
        var labels = block.Lines.OfType<AsmLabel>().Select(l => l.Name).Where(n => n.StartsWith('.')).ToHashSet();
        foreach (var line in block.Lines)
        {
            if (line is not AsmGeneratorCall g)
            {
                lines.Add(line);
                continue;
            }
            if (Lookup(g.Call.Name) is FunctionSymbol)
                throw new CompileError(g.Pos, $"'{g.Call.Name}' is a function, which runs on the 6502. Call it with 'jsr {g.Call.Name}'");
            lines.AddRange(CompileTime.Interpreter.Generate(g.Call, this, ref numbers, labels));
        }
        block.Lines.Clear();
        block.Lines.AddRange(lines);
    }

    /// <summary>Evaluates an operand: a number, or an address (variable, function, label) plus a constant.</summary>
    private AsmValue AsmOperand(Expr e, Dictionary<string, AsmLabel> labels)
    {
        switch (e)
        {
            case AsmLabelExpr l:
                return labels.TryGetValue(l.Name, out var label)
                    ? new AsmValue(0, Label: label)
                    : throw new CompileError(l.Pos, $"Label '{l.Name}' is not defined in this asm block. Define it with '.{l.Name}:' on a line of the block");

            case NameExpr n:
                switch (Named(n.Bound, n.Name) ?? Lookup(n.Name))
                {
                    case null: throw NotDeclared(n.Name, n.Pos);
                    case ConstSymbol { Real: not null }: throw InRuntime(n);
                    case ConstSymbol c: return new AsmValue(c.Value);
                    case FunctionSymbol f: return new AsmValue(0, Function: f);
                    case VariableSymbol v:
                        if (!v.InMemory)
                            throw new CompileError(n.Pos, v.Kind == VariableKind.Parameter
                                ? $"'{n.Name}' is passed in register {v.Register}; use the register directly"
                                : $"'{n.Name}' lives in register {v.Register}; use the register directly");
                        n.Symbol = v;
                        UseGlobal(v, n.Pos);
                        v.Weight += Weight();
                        return new AsmValue(0, Variable: v);
                }
                throw new InvalidOperationException();

            case MemberExpr m when m.Member is not ("lo" or "hi"):
            {
                // A field of a struct variable: its address, e.g. sta vic.border.
                CheckMemberTarget(m);
                CheckExpr(m.Target);
                if (!(m.Target.Type.IsStruct || m.Target.Type is { IsPointer: true, Element.IsStruct: true }))
                    throw new CompileError(m.Pos, $"Unknown member '.{m.Member}'; assembly only has .lo and .hi, and fields of struct variables. Use one of those");
                CheckField(m);
                if (m.Lowered is NameExpr { Symbol.AliasOf: { } storage } view)
                    return new AsmValue(view.Symbol!.AliasOffset, Variable: storage);
                if (m.Place is { Kind: PlaceKind.Memory } place)
                    return new AsmValue(place.Offset, Variable: place.Base);
                throw new CompileError(m.Pos,
                    "In assembly, a field must belong to a struct variable (lda player.hp). Fields through a pointer or in an array of structs have no fixed address. Read them with an index register: ldy #offset(T.field) and lda (p),y");
            }

            case MemberExpr m:
            {
                CheckMemberTarget(m);
                var inner = AsmOperand(m.Target, labels);
                bool high = m.Member == "hi";
                if (inner.High is not null) throw new CompileError(m.Pos, $".{m.Member} of a value that is already one byte. Remove one '.{m.Member}'");
                if (inner.IsNumber) return new AsmValue(high ? (inner.Number >> 8) & 0xFF : inner.Number & 0xFF);
                return inner with { High = high };
            }

            case BinaryExpr b:
            {
                var l = AsmOperand(b.Left, labels);
                var r = AsmOperand(b.Right, labels);
                if (l.IsNumber && r.IsNumber) return new AsmValue(FoldAsm(b, l.Number, r.Number));
                if (!l.IsNumber && l.High is null && r.IsNumber && b.Op is TokenKind.Plus or TokenKind.Minus)
                    return l with { Number = l.Number + (b.Op == TokenKind.Plus ? r.Number : -r.Number) };
                if (!r.IsNumber && r.High is null && l.IsNumber && b.Op == TokenKind.Plus)
                    return r with { Number = r.Number + l.Number };
                throw new CompileError(b.Pos, "In assembly, an address can only have a constant added or subtracted. Write e.g. name+1 or (name+1).hi");
            }

            case UnaryExpr { Op: TokenKind.Minus or TokenKind.Plus or TokenKind.Tilde } u:
            {
                var inner = AsmOperand(u.Operand, labels);
                if (!inner.IsNumber) throw new CompileError(u.Pos, "Only numbers can be negated or inverted. Use a constant here, not an address");
                return new AsmValue(u.Op switch { TokenKind.Minus => ConstNegate(u.Pos, inner.Number), TokenKind.Tilde => ~inner.Number, _ => inner.Number });
            }
        }

        // Literals, len(), sizeof(), casts of constants.
        CheckExpr(e);
        if (e.ConstValue is long value) return new AsmValue(value);
        throw new CompileError(e.Pos, "An assembly operand must be a constant, or the name of a variable, function or .label. Declare a constant for a computed value");
    }

    private static long FoldAsm(BinaryExpr b, long l, long r) => b.Op switch
    {
        TokenKind.Slash or TokenKind.Percent when r == 0 => throw new CompileError(b.Pos, "Division by zero. Check the divisor"),
        TokenKind.Plus or TokenKind.Minus or TokenKind.Star or TokenKind.Slash or TokenKind.Percent
            or TokenKind.Amp or TokenKind.Pipe or TokenKind.Caret => ConstArithmetic(b.Pos, b.Op, l, r),
        TokenKind.Shl or TokenKind.Shr when r is >= 0 and < 64 => ConstArithmetic(b.Pos, b.Op, l, r),
        TokenKind.Shl or TokenKind.Shr => throw new CompileError(b.Right.Pos, "Shift count must be 0 to 63. Use a count in that range"),
        _ => throw new CompileError(b.Pos, "Assembly operands can only use + - * / % & | ^ << >>. Declare a constant for anything else"),
    };

    /// <summary>
    /// Picks the addressing mode from how the operand is written. Memory operands get the absolute
    /// modes; the assembler uses the zero-page form when the address turns out to be below $100.
    /// </summary>
    private static AddressingMode AsmMode(AsmInstruction ins, AsmValue? v)
    {
        var m = ins.Mnemonic;
        string name = m.ToString().ToLowerInvariant();
        bool Has(AddressingMode mode) => InstructionSet.TryGet(m, mode, out _);
        // The code generator keeps the offset in an int. The assembler checks the address itself.
        if (v is { IsNumber: false, Number: < -0xFFFF or > 0xFFFF })
            throw new CompileError(ins.Operand!.Pos, $"Offset {v.Number} from an address is outside memory. Use a smaller offset");

        switch (ins.Form)
        {
            case AsmForm.None:
                if (Has(Implied)) return Implied;
                if (Has(Accumulator)) return Accumulator;
                throw new CompileError(ins.Pos, $"'{name}' needs an operand. Write one after it, e.g. {name} #0 or {name} name");
            case AsmForm.Accumulator:
                return Accumulator;
            case AsmForm.Immediate:
                if (!Has(Immediate)) throw new CompileError(ins.Pos, $"'{name}' has no immediate mode (#). Remove '#' to use the address, or use another instruction");
                if (v!.IsNumber && v.Number is < -128 or > 255)
                    throw new CompileError(ins.Operand!.Pos, $"#{v.Number} does not fit in a byte. Use a value from -128 to 255, or .lo and .hi of it");
                if (!v.IsNumber && v.High is null)
                    throw new CompileError(ins.Operand!.Pos, "An address has two bytes. Write #name.lo or #name.hi");
                return Immediate;
        }

        if (Has(Relative))
        {
            if (ins.Form != AsmForm.Direct || ins.Index is not null || v!.Label is null && v.Function is null || v.High is not null)
                throw new CompileError(ins.Pos, $"'{name}' needs a label, e.g. {name} .loop");
            return Relative;
        }
        if (v!.High is not null)
            throw new CompileError(ins.Operand!.Pos, ".lo and .hi give a byte value, not an address. Use it as an immediate: #name.lo");
        if (v.IsNumber && v.Number is < 0 or > 0xFFFF)
            throw new CompileError(ins.Operand!.Pos, $"Address {v.Number} is outside memory. Use an address from $0000 to $FFFF");

        switch (ins.Form)
        {
            case AsmForm.Direct when ins.Index is null:
                if (Has(Absolute)) return Absolute;
                throw new CompileError(ins.Pos, $"'{name}' takes no operand. Remove it");
            case AsmForm.Direct:
            {
                var (abs, zp) = ins.Index == Register.X ? (AbsoluteX, ZeroPageX) : (AbsoluteY, ZeroPageY);
                string form = $"address,{ins.Index.ToString()!.ToLowerInvariant()}";
                if (Has(abs)) return abs;
                if (Has(zp))
                {
                    RequireZeroPage(ins, v, $"'{name} {form}'");
                    return zp;
                }
                throw new CompileError(ins.Pos, $"'{name}' has no {form} mode. Use another addressing mode or instruction");
            }
            case AsmForm.Indirect:
                if (Has(Indirect)) return Indirect;
                throw new CompileError(ins.Pos, $"'{name}' has no (address) mode. Write (pointer),y to read through a pointer");
            default:
            {
                var mode = ins.Form == AsmForm.IndexedIndirect ? IndexedIndirect : IndirectIndexed;
                string form = mode == IndexedIndirect ? "(address,x)" : "(address),y";
                if (!Has(mode)) throw new CompileError(ins.Pos, $"'{name}' has no {form} mode. Use another addressing mode or instruction");
                RequireZeroPage(ins, v, $"'{name} {form}'");
                return mode;
            }
        }
    }

    /// <summary>The operand of a zero-page-only mode must be a zero-page address. Variables are moved there.</summary>
    private static void RequireZeroPage(AsmInstruction ins, AsmValue v, string what)
    {
        var pos = ins.Operand!.Pos;
        if (v.IsNumber)
        {
            if (v.Number > 0xFF)
                throw new CompileError(pos, $"{what} needs a zero-page address ($00-$FF), not ${v.Number:X4}. Use a variable in zero page");
            return;
        }
        if (v.Variable is not { } var)
            throw new CompileError(pos, $"{what} needs a zero-page address, not a {(v.Function is not null ? "function" : "label")}. Use a variable in zero page");
        // Data is never moved into zero page (on a cartridge it is ROM): the operand is almost always meant to be a pointer to it.
        if (var.IsData)
            throw new CompileError(pos, ins.Form is AsmForm.IndexedIndirect or AsmForm.IndirectIndexed
                ? $"{what} needs a pointer in zero page, but '{var.Name}' is data, not a pointer. Declare one, as in 'var p: ptr u8 = addr({var.Name})', and use (p),y"
                : $"{what} needs a zero-page address, but '{var.Name}' is data, which is never in zero page. Use another addressing mode, or a variable in zero page");
        if (var.FixedAddress is int a && a + v.Number > 0xFF)
            throw new CompileError(pos, $"{what} needs a zero-page address, but '{var.Name}' is at ${a:X4}. Place it in zero page ('@ zp' or an address below $100)");
        var.AsmZeroPage = true;
    }

    private void AddEffects(AsmInstruction ins, AsmEffects effects)
    {
        var (reads, writes) = AsmEffects.Of(ins.Mnemonic, ins.Mode);
        var routine = ins.Mnemonic == Mnemonic.Jsr && ins.Value?.Function is { FixedAddress: not null } r ? r : null;
        if (routine is not null)
            foreach (var kept in routine.Keeps)
                writes &= ~(kept switch { Register.A => CpuState.A, Register.X => CpuState.X, _ => CpuState.Y });
        effects.Reads |= reads;
        effects.Writes |= writes;
        if (ins.Mnemonic == Mnemonic.Jsr) effects.Calls = true;
        // sta g+1: the assembly patches the code of g, so the optimizer cannot trust g's own instructions.
        if (ins.Value?.Function is { } patched && (AsmEffects.WritesMemory(ins.Mnemonic, ins.Mode) || ins.Mnemonic is Mnemonic.Sta or Mnemonic.Stx or Mnemonic.Sty))
            patched.CodePatched = true;

        // A register that holds a loop variable must survive the block.
        foreach (var reg in _loopRegisters)
        {
            if (ins.Mnemonic == Mnemonic.Jsr && routine?.Keeps.Contains(reg) != true)
                throw new CompileError(ins.Pos,
                    $"'jsr' calls a subroutine, which can change {reg}, the register of the loop variable. Remove 'using {reg}' from the loop, or call a routine that keeps {reg}");
            if (writes.HasFlag(reg == Register.X ? CpuState.X : CpuState.Y))
                throw new CompileError(ins.Pos,
                    $"This changes {reg}, which holds the loop variable. Remove 'using {reg}' from the loop, or leave {reg} unchanged");
        }

        var v = ins.Value;
        if (v?.Function is { IsInterrupt: true } handler)
        {
            if (ins.Mnemonic == Mnemonic.Jsr)
                throw new CompileError(ins.Operand!.Pos,
                    $"'{handler.Name}' is an interrupt handler: it ends with rti, so jsr cannot call it. Install its address instead: lda #{handler.Name}.lo");
            // Naming a handler (to install it) keeps it in the program, as a root of its own.
            if (!_dead) _function!.UsedInterrupts.Add(handler);
        }
        else if (v?.Function is { IsInline: true } inlined)
            throw new CompileError(ins.Operand!.Pos,
                $"'{inlined.Name}' is inline: it is copied into each Tern caller and has no address of its own. Call it from Tern, or remove 'inline'");
        else if (v?.Function is { FixedAddress: null } named && v.High is not null)
        {
            // #f.lo / #f.hi takes the function's address, as addr(f) does (spec 6.5). Assembly may
            // take it even with memory parameters: it can set them itself before calling.
            CheckSiblingAddress(named, ins.Operand!.Pos);
            if (!_dead)
            {
                named.AddressTaken = true;
                _function!.UsedAddresses.Add(named);
            }
        }
        else if (v?.Function is { } f && (f != _function || ins.Mnemonic == Mnemonic.Jsr))
            AddCall(_function!, f, ins.Operand!.Pos);
        // Assembly cannot write a function's memory parameters (they are not names outside it).
        if (v?.Function is { FixedAddress: null } callee && callee != _function && v.High is null
            && ins.Mnemonic is Mnemonic.Jsr or Mnemonic.Jmp && ins.Mode == Absolute
            && callee.Parameters.FirstOrDefault(p => p.PassedIn is null) is { } memoryParam)
            throw new CompileError(ins.Operand!.Pos,
                $"'{callee.Name}' takes '{memoryParam.Name}' in memory, which assembly cannot set. "
                + $"Pass it in a register ({memoryParam.Name}: {memoryParam.Type} using A), or call {callee.Name} from Tern");
        if (v?.Variable is not { } variable) return;
        if (v.High is not null)
        {
            // #name.lo / #name.hi: the address is used, perhaps as a pointer.
            variable.AddressTaken = true;
            return;
        }
        if (ins.Mode == Indirect)
        {
            // jmp ($xxFF) reads the high byte from $xx00 on the NMOS 6502.
            if (variable.FixedAddress is int fixedAt && ((fixedAt + v.Number) & 0xFF) == 0xFF)
                throw new CompileError(ins.Operand!.Pos,
                    $"jmp (...) at ${fixedAt + v.Number:X4} reads its high byte from ${(fixedAt + v.Number) & 0xFF00:X4} on the 6502, since the address ends in $FF. Move '{variable.Name}'");
            variable.JumpVectorOffsets.Add((int)v.Number);
        }
        if (AsmEffects.ReadsMemory(ins.Mnemonic, ins.Mode)) effects.VariablesRead.Add(variable);
        if (AsmEffects.WritesMemory(ins.Mnemonic, ins.Mode))
        {
            // On a cartridge, data is ROM: a store leaves it as it is and reaches the board's latch, as
            // uxrom.select's bus-conflict table needs (provisional, question 159).
            if (variable.IsData && _platform.Boards.Count > 0) return;
            if (variable.IsData) throw new CompileError(ins.Operand!.Pos, $"'{variable.Name}' is data, which is read-only. Declare it with 'var' to change it");
            if (variable.ReadOnly)
                throw new CompileError(ins.Operand!.Pos, $"Loop variable '{variable.Name}' cannot be changed inside the loop. Use a 'while' loop to change the counter yourself");
            effects.VariablesWritten.Add(variable);
        }
    }
}
